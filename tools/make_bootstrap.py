"""Regenerate bootstrap.sh from the workflow-observability folder.

Run from the repo root after changing any project file:
    python3 tools/make_bootstrap.py
"""
import os

ROOT = "workflow-observability"
files = sorted(os.path.join(d, f) for d, _, fs in os.walk(ROOT) for f in fs if "__pycache__" not in d)
files.append(".github/workflows/deploy.yml")

out = [
    "#!/usr/bin/env bash",
    "# Recreates the workflow-observability project from scratch.",
    "# Usage:  bash bootstrap.sh            -> creates ./workflow-observability",
    "#         bash bootstrap.sh <target>   -> creates <target>/workflow-observability",
    "# Works on macOS, Linux, WSL and Git Bash on Windows.",
    "# Generated by tools/make_bootstrap.py - do not edit by hand.",
    "set -euo pipefail",
    'BASE="${1:-.}"',
    'mkdir -p "$BASE" && cd "$BASE"',
    "",
    "write() {  # write <path>  (content on stdin)",
    '  mkdir -p "$(dirname "$1")"',
    '  cat > "$1"',
    '  echo "  created $1"',
    "}",
    "",
    'echo "Creating workflow-observability project in $(pwd)"',
    "",
]
for p in files:
    dest = p if p.startswith(ROOT) else os.path.join(ROOT, p)
    content = open(p).read()
    assert "WFOBS_EOF" not in content, f"delimiter found in {p}"
    out += [f"write '{dest}' <<'WFOBS_EOF'", content.rstrip("\n"), "WFOBS_EOF", ""]
out += [
    "echo",
    'echo "Done. $(find workflow-observability -type f | wc -l | tr -d " ") files created."',
    'echo "Next: open workflow-observability/STEP_BY_STEP.md and start at Step 2."',
    'echo "Note: .github/ is placed inside workflow-observability/; move it to your repo root if you use GitHub Actions."',
]
with open("bootstrap.sh", "w", newline="\n") as f:
    f.write("\n".join(out) + "\n")
print(f"bootstrap.sh written with {len(files)} files")
